package domain

// MaxNameLen — предел длины ОДНОГО имени в байтах UTF-8 после нормализации NFC
// (§5.3 п. 6).
//
// Значение уже зафиксировано в `internal/proto/proto.go:33` и объявляется здесь
// второй раз не по недосмотру: проверку имени выполняет `internal/metadata`, а
// он не вправе импортировать `proto` (§4.3 п. 1). Совпадение двух объявлений
// проверяется тестом — тем же способом, что и совпадение проводных кодов
// ChecksumAlgo.
const MaxNameLen = 255

// MaxPathLen — предел длины полного VirtualPath в байтах (§5.3 п. 7).
//
// Объявлено здесь по той же причине, что и MaxNameLen: значение живёт в
// `internal/proto/proto.go:32`, а разбирает путь сервисный слой, которому proto
// недоступен (§4.3 п. 1). Совпадение проверяется тестом: предел, больший
// проводного, дал бы путь, который сервер принимает, а кадр передать не в
// состоянии.
const MaxPathLen = 4096

// MaxTreeDepth — предел числа компонентов пути НИЖЕ virtual root (§5.3 п. 8).
//
// Ограничение не косметическое: тем же значением §9.3, §9.4 и §21.3 ограничивают
// рекурсивные обходы дерева, а parent_id в `resources` цикл выразить может
// (испорченная БД, ручная правка), и обход без предела на таком дереве не
// завершается. Проводного аналога у величины нет: глубина — свойство дерева, а
// не кадра.
const MaxTreeDepth = 64
