package users

import (
	"context"
	"sync"

	"github.com/vitikevich-landau/go_fileshare/internal/domain"
)

// userLocks сериализует операции §7.4 по пользователю.
//
// Зачем это нужно, хотя SQLite и так сериализует запись. Каждая команда §7.4
// состоит из ДВУХ фаз: транзакция меняет строку users, а затем applyRevocation
// приводит в соответствие сессии, токены и ссылки. Вторая фаза лежит вне
// транзакции по необходимости — сессии и токены живут в памяти процесса, а не в
// БД (§16.3 не заводит для них таблиц в §6). Без внешней сериализации commit'ы
// упорядочены, а фазы отзыва — нет:
//
//	`user enable`  коммитит active   ──┐
//	`user disable` коммитит disabled ──┼─ порядок в БД: enable, disable
//	`user disable` переводит ссылки в suspended
//	`user enable`  переводит ссылки в active   ← отзыв опоздал
//
// В итоге БД говорит «пользователь отключён», обе команды вернули успех, а
// публичные ссылки остались рабочими. Тот же порядок ломает и отзыв сессий.
//
// Примитив намеренно per-user, а не глобальный: команды к разным пользователям
// независимы, и запирать их друг о друга незачем. И это ТОТ САМЫЙ per-user
// примитив, который §7.4 п. 8 требует разделить с допуском сессии в реестр:
// провязывая Sessions в B1 (§26), допуск нужно завести под этот же замок, иначе
// рукопожатие в полёте снова разъедется со сменой пароля.
//
// Записи из карты не удаляются: их число ограничено числом пользователей, а
// подсчёт ссылок ради освобождения одного мьютекса на учётку стоил бы дороже
// самой памяти.
type userLocks struct {
	mu sync.Mutex
	m  map[domain.UserID]chan struct{}
}

func newUserLocks() *userLocks {
	return &userLocks{m: make(map[domain.UserID]chan struct{})}
}

// acquire занимает замок пользователя и возвращает функцию освобождения.
//
// Замок построен на канале, а не на sync.Mutex, ровно ради ctx: команда,
// пришедшая по сети, обязана уметь отмениться, пока стоит в очереди, а
// sync.Mutex.Lock отмену не поддерживает. При отмене замок НЕ занят, и
// возвращённая ошибка — ctx.Err().
func (l *userLocks) acquire(ctx context.Context, id domain.UserID) (func(), error) {
	l.mu.Lock()
	ch, ok := l.m[id]
	if !ok {
		ch = make(chan struct{}, 1)
		l.m[id] = ch
	}
	l.mu.Unlock()

	select {
	case ch <- struct{}{}:
		return func() { <-ch }, nil
	case <-ctx.Done():
		return nil, ctx.Err()
	}
}
